import { stringify } from 'yaml';

type KubernetesObject = Record<string, unknown>;

export interface WorkerDefinition {
  /** Value passed as `--module`. */
  module: string;
  /** Value passed as `--schema`. Default: the module name. `false` leaves the flag out. */
  schema?: string | false;
  /** Shorter name used in resource names, to stay within Kubernetes name limits. Default: the module name. */
  alias?: string;
  /** Value passed as `--limit`. Default: 10. */
  limit?: number;
  /** Extra command line arguments, for example topology overrides. */
  args?: string[];
  resources?: KubernetesObject;
  /** Extra environment variables of the container. */
  env?: KubernetesObject[];
  volumes?: KubernetesObject[];
  volumeMounts?: KubernetesObject[];
}

export interface DispatcherDefinition extends WorkerDefinition {
  /** Cron schedule. Default: every minute. */
  schedule?: string;
}

export interface ConsumerDefinition extends WorkerDefinition {
  /** Default: 1. */
  replicas?: number;
  /** Time the pod gets to finish in-flight messages. Default: the Kubernetes default (30s). */
  terminationGracePeriodSeconds?: number;
}

export interface WorkerManifestsConfig {
  /** Default: `{KUB_SERVICE_NAME}`, substituted at deploy time. */
  serviceName?: string;
  /** Default: `{KUB_NAMESPACE_PREFIX}-{BUILD_ENV}`. */
  namespace?: string;
  /** Default: `localhost:32000/image:latest`, substituted at deploy time. */
  image?: string;
  /** Default: `Always`. */
  imagePullPolicy?: string;
  /** Default: `['gcr-secret']`. */
  imagePullSecrets?: string[];
  /** Default: the service ConfigMap, the service Secret and `rabbitmq-credentials`. */
  envFrom?: KubernetesObject[];
  /** Default: 100m/256Mi requested, 250m/512Mi limit. */
  resources?: KubernetesObject;
  /**
   * How the worker process is launched. By default through the npm scripts,
   * `npm run <command> -- <args>` in a shell. Give the executable instead, for
   * example `['dumb-init', 'node', 'dist/message-bus-cli.js']`, to run it
   * without a shell so that SIGTERM reaches it and consumers stop gracefully.
   */
  entrypoint?: string[];
  /**
   * Sample values of the `{PLACEHOLDER}`s, used only to check name lengths,
   * for example `{ KUB_SERVICE_NAME: 'padmasana-service' }`.
   */
  placeholders?: Record<string, string>;
  /** One CronJob each, running `dispatch-messages`. */
  dispatchers?: DispatcherDefinition[];
  /** One Deployment each, running `handle-messages`. */
  consumers?: ConsumerDefinition[];
}

export interface GeneratedManifest {
  kind: 'CronJob' | 'Deployment';
  name: string;
  fileName: string;
  manifest: KubernetesObject;
  yaml: string;
}

const CRON_JOB_NAME_LIMIT = 52;
const NAME_LIMIT = 63;
const HEADER = '# Generated by rabbitmq-bus-k8s. Change the generator config, not this file.\n';

const DEFAULT_RESOURCES = {
  requests: { cpu: '100m', memory: '256Mi' },
  limits: { cpu: '250m', memory: '512Mi' },
};

interface Resolved {
  serviceName: string;
  namespace: string;
  image: string;
  imagePullPolicy: string;
  imagePullSecrets: string[];
  envFrom: KubernetesObject[];
  resources: KubernetesObject;
  entrypoint?: string[];
  placeholders: Record<string, string>;
}

function resolve(config: WorkerManifestsConfig): Resolved {
  const serviceName = config.serviceName ?? '{KUB_SERVICE_NAME}';

  return {
    serviceName,
    namespace: config.namespace ?? '{KUB_NAMESPACE_PREFIX}-{BUILD_ENV}',
    image: config.image ?? 'localhost:32000/image:latest',
    imagePullPolicy: config.imagePullPolicy ?? 'Always',
    imagePullSecrets: config.imagePullSecrets ?? ['gcr-secret'],
    envFrom: config.envFrom ?? [
      { configMapRef: { name: `${serviceName}-config` } },
      { secretRef: { name: `${serviceName}-secrets` } },
      { secretRef: { name: 'rabbitmq-credentials' } },
    ],
    resources: config.resources ?? DEFAULT_RESOURCES,
    entrypoint: config.entrypoint,
    placeholders: config.placeholders ?? {},
  };
}

function command(
  resolved: Resolved,
  name: 'dispatch-messages' | 'handle-messages',
  worker: WorkerDefinition,
): string[] {
  const schema = worker.schema ?? worker.module;
  const args = [
    '--limit',
    String(worker.limit ?? 10),
    `--module=${worker.module}`,
    ...(schema === false ? [] : [`--schema=${schema}`]),
    ...(worker.args ?? []),
  ];

  if (resolved.entrypoint) return [...resolved.entrypoint, name, ...args];
  return ['/bin/sh', '-c', `npm run ${name} -- ${args.join(' ')}`];
}

function container(
  resolved: Resolved,
  name: string,
  commandLine: string[],
  worker: WorkerDefinition,
): KubernetesObject {
  return {
    name,
    image: resolved.image,
    imagePullPolicy: resolved.imagePullPolicy,
    envFrom: resolved.envFrom,
    ...(worker.env?.length ? { env: worker.env } : {}),
    ...(worker.volumeMounts?.length ? { volumeMounts: worker.volumeMounts } : {}),
    command: commandLine,
    resources: worker.resources ?? resolved.resources,
  };
}

function expand(value: string, placeholders: Record<string, string>): string {
  return value.replace(/\{(\w+)\}/g, (match, key) => placeholders[key] ?? match);
}

function assertLength(
  problems: string[],
  placeholders: Record<string, string>,
  what: string,
  value: string,
  limit: number,
): void {
  const expanded = expand(value, placeholders);
  if (expanded.length > limit) {
    problems.push(
      `${what} "${expanded}" is ${expanded.length} characters long, the limit is ${limit}. Give the worker a shorter alias.`,
    );
  }
}

function dispatcherManifest(
  resolved: Resolved,
  dispatcher: DispatcherDefinition,
  problems: string[],
): GeneratedManifest {
  const alias = dispatcher.alias ?? dispatcher.module;
  const name = `${resolved.serviceName}-${alias}-dispatch-cronjob`;
  const containerName = `${resolved.serviceName}-${alias}-dispatcher`;

  assertLength(problems, resolved.placeholders, 'CronJob name', name, CRON_JOB_NAME_LIMIT);
  assertLength(problems, resolved.placeholders, 'Container name', containerName, NAME_LIMIT);

  const manifest = {
    apiVersion: 'batch/v1',
    kind: 'CronJob',
    metadata: {
      name,
      namespace: resolved.namespace,
      labels: { app: `${resolved.serviceName}-${dispatcher.module}` },
    },
    spec: {
      schedule: dispatcher.schedule ?? '*/1 * * * *',
      // A run that overlaps the previous one would publish the same records twice.
      concurrencyPolicy: 'Forbid',
      jobTemplate: {
        spec: {
          template: {
            spec: {
              containers: [
                container(
                  resolved,
                  containerName,
                  command(resolved, 'dispatch-messages', dispatcher),
                  dispatcher,
                ),
              ],
              ...(dispatcher.volumes?.length ? { volumes: dispatcher.volumes } : {}),
              restartPolicy: 'OnFailure',
              imagePullSecrets: resolved.imagePullSecrets.map((secret) => ({
                name: secret,
              })),
            },
          },
        },
      },
    },
  };

  return {
    kind: 'CronJob',
    name,
    fileName: `dispatch-messages.${dispatcher.module}.cronjob.yml`,
    manifest,
    yaml: HEADER + stringify(manifest, { lineWidth: 0 }),
  };
}

function consumerManifest(
  resolved: Resolved,
  consumer: ConsumerDefinition,
  problems: string[],
): GeneratedManifest {
  const alias = consumer.alias ?? consumer.module;
  const app = `${resolved.serviceName}-${alias}-handler`;
  const name = `${app}-deployment`;
  const containerName = `${app}-container`;

  assertLength(problems, resolved.placeholders, 'Label value', app, NAME_LIMIT);
  assertLength(problems, resolved.placeholders, 'Container name', containerName, NAME_LIMIT);

  const manifest = {
    apiVersion: 'apps/v1',
    kind: 'Deployment',
    metadata: {
      labels: { app },
      name,
      namespace: resolved.namespace,
    },
    spec: {
      replicas: consumer.replicas ?? 1,
      selector: { matchLabels: { app } },
      strategy: {
        type: 'RollingUpdate',
        rollingUpdate: { maxSurge: '25%', maxUnavailable: '25%' },
      },
      template: {
        metadata: { labels: { app, namespace: resolved.namespace } },
        spec: {
          imagePullSecrets: resolved.imagePullSecrets.map((secret) => ({
            name: secret,
          })),
          ...(consumer.terminationGracePeriodSeconds !== undefined
            ? {
                terminationGracePeriodSeconds:
                  consumer.terminationGracePeriodSeconds,
              }
            : {}),
          containers: [
            container(
              resolved,
              containerName,
              command(resolved, 'handle-messages', consumer),
              consumer,
            ),
          ],
          ...(consumer.volumes?.length ? { volumes: consumer.volumes } : {}),
        },
      },
    },
  };

  return {
    kind: 'Deployment',
    name,
    fileName: `handle-messages.${consumer.module}.yml`,
    manifest,
    yaml: HEADER + stringify(manifest, { lineWidth: 0 }),
  };
}

/**
 * Builds the Kubernetes manifests of the message bus workers: a CronJob per
 * outbox dispatcher and a Deployment per consumer. Throws when a generated
 * name breaks a Kubernetes limit.
 */
export function generateWorkerManifests(
  config: WorkerManifestsConfig,
): GeneratedManifest[] {
  const resolved = resolve(config);
  const problems: string[] = [];

  const modules = [
    ...(config.dispatchers ?? []).map((worker) => `dispatcher:${worker.module}`),
    ...(config.consumers ?? []).map((worker) => `consumer:${worker.module}`),
  ];
  const duplicate = modules.find((module, index) => modules.indexOf(module) !== index);
  if (duplicate) problems.push(`Declared twice: ${duplicate.replace(':', ' ')}.`);
  if ([...(config.dispatchers ?? []), ...(config.consumers ?? [])].some((worker) => !worker.module)) {
    problems.push('Every worker needs a module.');
  }

  const manifests = [
    ...(config.dispatchers ?? []).map((dispatcher) =>
      dispatcherManifest(resolved, dispatcher, problems),
    ),
    ...(config.consumers ?? []).map((consumer) =>
      consumerManifest(resolved, consumer, problems),
    ),
  ];

  if (problems.length) {
    throw new Error(`Invalid worker manifests:\n- ${problems.join('\n- ')}`);
  }

  return manifests;
}
